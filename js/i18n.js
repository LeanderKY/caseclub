let LANG = localStorage.getItem('cc_lang') || 'en';
function t(key){
  const v = (T[LANG] && T[LANG][key] !== undefined) ? T[LANG][key] : T.en[key];
  return v !== undefined ? v : key;
}
function setLang(lang){
  if(!LANGS.includes(lang)) return;
  LANG = lang;
  localStorage.setItem('cc_lang', lang);
  document.documentElement.lang = lang;
  applyI18n();
  if(typeof onLangChange === 'function') onLangChange();
}
function applyI18n(){
  document.querySelectorAll('[data-i]').forEach(el=>{
    el.innerHTML = t(el.dataset.i);
  });
  document.querySelectorAll('.lang-opt').forEach(b=>{
    b.classList.toggle('active', b.dataset.lang === LANG);
  });
  const lb = document.getElementById('langBtnLabel');
  if(lb) lb.textContent = LANG.toUpperCase();
}
